export async function seedDefaultDataForOrg(organizationId: string) {
  // 1. Seed Accounts
  for (const account of defaultAccounts) {
    const masterAccount = await prisma.masterAccount.findUnique({
      where: { code: account.code }
    });

    // Динамически вычисляем корректный тип и признак постируемости
    const accountType = classifyAccountType(account.code)
    const postable = isPostable(account.code)

    await prisma.account.upsert({
      where: { 
        code_organization_id: {
          code: account.code,
          organization_id: organizationId
        }
      },
      update: { 
        name: account.name, 
        type: accountType,
        is_postable: postable,
        master_account_id: masterAccount?.id || null 
      },
      create: {
        code: account.code,
        name: account.name,
        type: accountType,
        is_postable: postable,
        organization_id: organizationId,
        master_account_id: masterAccount?.id || null
      },
    })
  }

  const now = new Date();
  const openingBalanceDate = new Date(now.getFullYear(), now.getMonth(), 1);
  const closedPeriodDate = new Date(openingBalanceDate);
  closedPeriodDate.setDate(closedPeriodDate.getDate() - 1);

  // 2. Initial system settings
  await prisma.systemSettings.upsert({
    where: { organization_id: organizationId },
    update: {},
    create: {
      opening_balance_date: openingBalanceDate,
      closed_period_date: closedPeriodDate,
      organization_id: organizationId
    },
  })
}
